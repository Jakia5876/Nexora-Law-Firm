-- 1. Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. Automatic updated_at trigger function
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 3. Users table
CREATE TABLE IF NOT EXISTS public.users (
    user_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    address     VARCHAR(200),
    phone       VARCHAR(30)  NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    email       VARCHAR(120) NOT NULL UNIQUE,
    role        TEXT CHECK (role IN ('admin', 'lawyer', 'assistant', 'client')) DEFAULT 'client' NOT NULL,
    is_active   BOOLEAN DEFAULT TRUE NOT NULL,
    created_at  TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at  TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_users_role  ON public.users(role);

DROP TRIGGER IF EXISTS trg_users_updated_at ON public.users;
CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 4. Court table
CREATE TABLE IF NOT EXISTS public.court (
    court_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_name   VARCHAR(255) NOT NULL,
    jurisdiction VARCHAR(150),
    user_id      BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    created_at   TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_court_user ON public.court(user_id);

-- 5. Case Type table
CREATE TABLE IF NOT EXISTS public.case_type (
    case_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_type    VARCHAR(100) NOT NULL,
    description  TEXT,
    user_id      BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    created_at   TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_type_user ON public.case_type(user_id);

-- 6. Assistant table
CREATE TABLE IF NOT EXISTS public.assistant (
    assistant_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assistant_name VARCHAR(255) NOT NULL,
    email          VARCHAR(120),
    phone          VARCHAR(30),
    user_id        BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    created_at     TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at     TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_assistant_user ON public.assistant(user_id);

DROP TRIGGER IF EXISTS trg_assistant_updated_at ON public.assistant;
CREATE TRIGGER trg_assistant_updated_at
BEFORE UPDATE ON public.assistant
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 7. Cases table
CREATE TABLE IF NOT EXISTS public.cases (
    case_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id        BIGINT NOT NULL REFERENCES public.court(court_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    case_no         VARCHAR(100) NOT NULL UNIQUE,
    under_section   VARCHAR(150) NOT NULL,
    filing_date     DATE NOT NULL,
    plaintiff_name  VARCHAR(150) NOT NULL,
    defendants_name VARCHAR(150) NOT NULL,
    assistant_id    BIGINT REFERENCES public.assistant(assistant_id) ON UPDATE CASCADE ON DELETE SET NULL,
    client_mobile   VARCHAR(30) NOT NULL,
    user_id         BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    note            TEXT,
    on_behalf       VARCHAR(50) DEFAULT 'Plaintiff',
    case_type_id    BIGINT NOT NULL REFERENCES public.case_type(case_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    case_no_note    VARCHAR(100),
    status          TEXT CHECK (status IN ('active', 'pending', 'resolved', 'inactive')) DEFAULT 'active' NOT NULL,
    created_at      TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at      TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cases_user        ON public.cases(user_id);
CREATE INDEX IF NOT EXISTS idx_cases_court       ON public.cases(court_id);
CREATE INDEX IF NOT EXISTS idx_cases_type        ON public.cases(case_type_id);
CREATE INDEX IF NOT EXISTS idx_cases_assistant   ON public.cases(assistant_id);
CREATE INDEX IF NOT EXISTS idx_cases_status      ON public.cases(status);
CREATE INDEX IF NOT EXISTS idx_cases_filing_date ON public.cases(filing_date);

DROP TRIGGER IF EXISTS trg_cases_updated_at ON public.cases;
CREATE TRIGGER trg_cases_updated_at
BEFORE UPDATE ON public.cases
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 8. Case Detail table
CREATE TABLE IF NOT EXISTS public.case_detail (
    case_detail_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id         BIGINT NOT NULL REFERENCES public.cases(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    next_date       DATE NOT NULL,
    order_detail    TEXT,
    presiding_judge VARCHAR(150),
    hearing_summary TEXT,
    created_at      TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at      TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_detail_case      ON public.case_detail(case_id);
CREATE INDEX IF NOT EXISTS idx_case_detail_next_date ON public.case_detail(next_date);

DROP TRIGGER IF EXISTS trg_case_detail_updated_at ON public.case_detail;
CREATE TRIGGER trg_case_detail_updated_at
BEFORE UPDATE ON public.case_detail
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 9. Case Documents table (Private Vault)
CREATE TABLE IF NOT EXISTS public.case_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id     BIGINT NOT NULL REFERENCES public.cases(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    title       TEXT NOT NULL,
    category    TEXT DEFAULT 'Pleading' NOT NULL,
    file_name   TEXT NOT NULL,
    file_size   TEXT,
    file_url    TEXT NOT NULL,
    uploaded_by BIGINT REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    uploaded_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_documents_case ON public.case_documents(case_id);

-- 10. Contacts table
CREATE TABLE IF NOT EXISTS public.contacts (
    id         TEXT PRIMARY KEY,
    name       TEXT NOT NULL,
    email      VARCHAR(120),
    phone      VARCHAR(30),
    service    TEXT,
    message    TEXT,
    status     TEXT CHECK (status IN ('New', 'Contacted', 'Retained', 'Closed')) DEFAULT 'New' NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_contacts_status     ON public.contacts(status);
CREATE INDEX IF NOT EXISTS idx_contacts_created_at ON public.contacts(created_at);

-- 11. Subscriptions table
CREATE TABLE IF NOT EXISTS public.subscriptions (
    subscription_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    subscription_plan VARCHAR(50) NOT NULL,
    start_date        DATE NOT NULL,
    end_date          DATE NOT NULL,
    status            TEXT CHECK (status IN ('active', 'expired', 'pending', 'inactive')) DEFAULT 'pending' NOT NULL,
    payment_method    VARCHAR(50),
    transaction_id    VARCHAR(100),
    amount            NUMERIC(10,2) NOT NULL,
    created_at        TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 12. Audit Logs table
CREATE TABLE IF NOT EXISTS public.audit_logs (
    log_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    action     VARCHAR(50) NOT NULL,
    entity     VARCHAR(50) NOT NULL,
    entity_id  TEXT,
    details    JSONB,
    ip_address VARCHAR(45),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 13. Enable Row Level Security (RLS)
ALTER TABLE public.users          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.court          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.case_type      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.assistant      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cases          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.case_detail    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.case_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contacts       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subscriptions  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_logs     ENABLE ROW LEVEL SECURITY;

-- 14. Apply RLS Policies
CREATE POLICY "Public intake submissions permitted" ON public.contacts FOR INSERT TO anon, authenticated WITH CHECK (name IS NOT NULL AND length(name) > 0);
CREATE POLICY "Staff read access on contacts"       ON public.contacts FOR SELECT TO authenticated USING (true);
CREATE POLICY "Staff mutate access on contacts"     ON public.contacts FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Staff delete access on contacts"     ON public.contacts FOR DELETE TO authenticated USING (true);

CREATE POLICY "Authenticated users view directory"  ON public.users FOR SELECT TO anon, authenticated USING (is_active = true);
CREATE POLICY "Authenticated mutation on users"     ON public.users FOR INSERT TO authenticated WITH CHECK (email IS NOT NULL AND phone IS NOT NULL);
CREATE POLICY "Authenticated update on users"       ON public.users FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Authenticated delete on users"       ON public.users FOR DELETE TO authenticated USING (true);

CREATE POLICY "Read cases allowed for portal users" ON public.cases FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Authenticated insert on cases"       ON public.cases FOR INSERT TO authenticated WITH CHECK (case_no IS NOT NULL AND court_id IS NOT NULL);
CREATE POLICY "Authenticated update on cases"       ON public.cases FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Authenticated delete on cases"       ON public.cases FOR DELETE TO authenticated USING (true);

CREATE POLICY "Read case_detail allowed"            ON public.case_detail FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Authenticated insert on case_detail" ON public.case_detail FOR INSERT TO authenticated WITH CHECK (case_id IS NOT NULL AND next_date IS NOT NULL);
CREATE POLICY "Authenticated update on case_detail" ON public.case_detail FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Authenticated delete on case_detail" ON public.case_detail FOR DELETE TO authenticated USING (true);

CREATE POLICY "Read case_documents allowed"            ON public.case_documents FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Authenticated upload on case_documents" ON public.case_documents FOR INSERT TO authenticated WITH CHECK (case_id IS NOT NULL AND file_url IS NOT NULL);
CREATE POLICY "Authenticated delete on case_documents" ON public.case_documents FOR DELETE TO authenticated USING (true);

CREATE POLICY "Read court allowed"         ON public.court FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Mutate court authenticated" ON public.court FOR ALL    TO authenticated       USING (true) WITH CHECK (true);

CREATE POLICY "Read case_type allowed"         ON public.case_type FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Mutate case_type authenticated" ON public.case_type FOR ALL    TO authenticated       USING (true) WITH CHECK (true);

CREATE POLICY "Read assistant allowed"         ON public.assistant FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Mutate assistant authenticated" ON public.assistant FOR ALL    TO authenticated       USING (true) WITH CHECK (true);

CREATE POLICY "Read subscriptions allowed"         ON public.subscriptions FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Mutate subscriptions authenticated" ON public.subscriptions FOR ALL    TO authenticated       USING (true) WITH CHECK (true);

CREATE POLICY "Read audit_logs allowed"   ON public.audit_logs FOR SELECT TO authenticated USING (true);
CREATE POLICY "Insert audit_logs allowed" ON public.audit_logs FOR INSERT TO anon, authenticated WITH CHECK (action IS NOT NULL);

