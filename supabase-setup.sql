-- ------------------------------------------------------------------------------
-- POLICIES: contacts (Intake Isolation: Anon INSERT ONLY; Staff read/mutate)
-- ------------------------------------------------------------------------------
CREATE POLICY "Anon public intake insert only"
    ON public.contacts
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (name IS NOT NULL AND length(name) > 0);

CREATE POLICY "Admin only read contacts"
    ON public.contacts
    FOR SELECT
    TO authenticated
    USING (auth.jwt() ->> 'role' = 'service_role' OR auth.role() = 'authenticated');

CREATE POLICY "Admin only update contacts"
    ON public.contacts
    FOR UPDATE
    TO authenticated
    USING (auth.jwt() ->> 'role' = 'service_role' OR auth.role() = 'authenticated')
    WITH CHECK (auth.jwt() ->> 'role' = 'service_role' OR auth.role() = 'authenticated');

CREATE POLICY "Admin only delete contacts"
    ON public.contacts
    FOR DELETE
    TO authenticated
    USING (auth.jwt() ->> 'role' = 'service_role' OR auth.role() = 'authenticated');

