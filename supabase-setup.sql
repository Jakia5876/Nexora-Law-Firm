-- Enable UUID extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==============================================================================
-- 1. AUTOMATIC UPDATED_AT TRIGGER FUNCTION
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ==============================================================================
-- 2. USERS TABLE
-- Roles: 'admin', 'lawyer', 'client', 'assistant'
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(200),
    phone VARCHAR(20) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    role TEXT CHECK (role IN ('admin', 'lawyer', 'client', 'assistant')) DEFAULT 'client',
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ==============================================================================
-- 3. COURT TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.court (
    court_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_name VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_court_user ON public.court(user_id);

-- ==============================================================================
-- 4. SUBSCRIPTIONS TABLE
-- Status: 'active', 'expired', 'pending', 'inactive'
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.subscriptions (
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    subscription_plan VARCHAR(50) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status TEXT CHECK (status IN ('active', 'expired', 'pending', 'inactive')) DEFAULT 'pending',
    payment_method VARCHAR(50),
    transaction_id VARCHAR(100),
    amount NUMERIC(10,2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_subscription_user ON public.subscriptions(user_id);
CREATE INDEX IF NOT EXISTS idx_subscription_status ON public.subscriptions(status);

-- ==============================================================================
-- 5. CASE_TYPE TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.case_type (
    case_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_type VARCHAR(100) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_type_user ON public.case_type(user_id);

-- ==============================================================================
-- 6. ASSISTANT TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.assistant (
    assistant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assistant_name VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_assistant_user ON public.assistant(user_id);

CREATE TRIGGER trg_assistant_updated_at
BEFORE UPDATE ON public.assistant
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ==============================================================================
-- 7. CASES TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.cases (
    case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id BIGINT NOT NULL REFERENCES public.court(court_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    case_no VARCHAR(100) NOT NULL,
    under_section VARCHAR(100) NOT NULL,
    filing_date DATE NOT NULL,
    plaintiff_name VARCHAR(150) NOT NULL,
    defendants_name VARCHAR(150) NOT NULL,
    assistant_id BIGINT REFERENCES public.assistant(assistant_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    client_mobile VARCHAR(30) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    note VARCHAR(500),
    on_behalf VARCHAR(50),
    case_type_id BIGINT NOT NULL REFERENCES public.case_type(case_type_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    case_no_note VARCHAR(100),
    status TEXT CHECK (status IN ('active', 'inactive')) DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_user ON public.cases(user_id);
CREATE INDEX IF NOT EXISTS idx_case_court ON public.cases(court_id);
CREATE INDEX IF NOT EXISTS idx_case_assistant ON public.cases(assistant_id);
CREATE INDEX IF NOT EXISTS idx_case_type ON public.cases(case_type_id);
CREATE INDEX IF NOT EXISTS idx_case_no ON public.cases(case_no);

CREATE TRIGGER trg_cases_updated_at
BEFORE UPDATE ON public.cases
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ==============================================================================
-- 8. CASE_DETAIL TABLE (Hearing history, orders, and diary notes)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.case_detail (
    case_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES public.cases(case_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    next_date DATE NOT NULL,
    order_detail TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_detail_case ON public.case_detail(case_id);
CREATE INDEX IF NOT EXISTS idx_case_detail_next_date ON public.case_detail(next_date);

CREATE TRIGGER trg_case_detail_updated_at
BEFORE UPDATE ON public.case_detail
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ==============================================================================
-- 9. CASE_DOCUMENTS TABLE (Private Vault document attachments)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.case_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES public.cases(case_id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'Document',
    file_name TEXT NOT NULL,
    file_size TEXT,
    file_url TEXT NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_docs_case ON public.case_documents(case_id);

-- ==============================================================================
-- 10. CONTACTS TABLE (Website Consultation & Client Inquiries)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.contacts (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    service TEXT,
    message TEXT,
    status TEXT DEFAULT 'New',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

