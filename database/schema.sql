-- Public consultation intake: anonymous visitors may INSERT only (never read, update or delete).
DROP POLICY IF EXISTS "Anon public intake insert only" ON public.contacts;
CREATE POLICY "Anon public intake insert only"
    ON public.contacts FOR INSERT TO anon
    WITH CHECK (
        name IS NOT NULL AND length(name) BETWEEN 2 AND 100
        AND (email IS NOT NULL OR phone IS NOT NULL)
    );

-- Public website content: only published / active rows are visible to visitors.
DROP POLICY IF EXISTS "Public read active practice_areas" ON public.practice_areas;
CREATE POLICY "Public read active practice_areas"
    ON public.practice_areas FOR SELECT TO anon, authenticated USING (status = 'active');

DROP POLICY IF EXISTS "Public read active attorneys" ON public.attorneys;
CREATE POLICY "Public read active attorneys"
    ON public.attorneys FOR SELECT TO anon, authenticated USING (status = 'active');

DROP POLICY IF EXISTS "Public read published site_content" ON public.site_content;
CREATE POLICY "Public read published site_content"
    ON public.site_content FOR SELECT TO anon, authenticated USING (status = 'published');

-- Intentionally NO policies on: users, court, case_type, assistant, cases, case_detail,
-- case_documents, subscriptions, audit_logs, revoked_tokens, client_accounts, client_case_access,
-- case_events, notifications (service-role access only).
