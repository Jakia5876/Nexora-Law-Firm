-- 17. ROW LEVEL SECURITY (RLS)
-- Model: every table has RLS enabled. The application reads and writes private data ONLY through
-- server-side code that uses the service-role key (which bypasses RLS) after verifying the admin
-- session. Therefore private tables have NO policies: anon and authenticated roles get no access.
-- The only policies are the deliberate public ones below.
-- ==============================================================================
ALTER TABLE public.users          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.practice_areas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attorneys      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_content   ENABLE ROW LEVEL SECURITY;
