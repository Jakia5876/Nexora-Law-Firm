-- Purge helper: the app also deletes expired rows on every logout.
-- Optional schedule (Supabase pg_cron): SELECT cron.schedule('purge-revoked-tokens', '0 * * * *', 'SELECT public.purge_expired_revoked_tokens()');
CREATE OR REPLACE FUNCTION public.purge_expired_revoked_tokens()
RETURNS void LANGUAGE sql AS $$ DELETE FROM public.revoked_tokens WHERE expires_at < now(); $$;

