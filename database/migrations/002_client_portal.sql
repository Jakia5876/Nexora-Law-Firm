-- ==============================================================================
-- Migration 002 — Client portal: client accounts, case access, case timeline, notifications
-- Run on an EXISTING database (safe to run more than once). Adds new tables only;
-- no existing table or column is changed. All tables: RLS on, NO policies
-- (the app reaches them only with the server-side service-role key).
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.client_accounts (
    client_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(120) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    mobile        VARCHAR(30),
    password_hash TEXT NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at    TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_client_accounts_email ON public.client_accounts(lower(email));

CREATE TABLE IF NOT EXISTS public.client_case_access (
    client_id  BIGINT NOT NULL REFERENCES public.client_accounts(client_id) ON UPDATE CASCADE ON DELETE CASCADE,
    case_id    BIGINT NOT NULL REFERENCES public.cases(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    PRIMARY KEY (client_id, case_id)
);
CREATE INDEX IF NOT EXISTS idx_client_case_access_case ON public.client_case_access(case_id);

CREATE TABLE IF NOT EXISTS public.case_events (
    event_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id        BIGINT NOT NULL REFERENCES public.cases(case_id) ON UPDATE CASCADE ON DELETE CASCADE,
    event_type     TEXT NOT NULL DEFAULT 'note' CHECK (event_type IN ('filing', 'hearing', 'order', 'document', 'status', 'note')),
    title          VARCHAR(150) NOT NULL,
    description    VARCHAR(1000),
    event_date     DATE NOT NULL DEFAULT CURRENT_DATE,
    client_visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_case_events_case_date ON public.case_events(case_id, event_date DESC);

CREATE TABLE IF NOT EXISTS public.notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT NOT NULL REFERENCES public.client_accounts(client_id) ON UPDATE CASCADE ON DELETE CASCADE,
    case_id         BIGINT REFERENCES public.cases(case_id) ON UPDATE CASCADE ON DELETE SET NULL,
    subject         VARCHAR(200) NOT NULL,
    body            VARCHAR(1000) NOT NULL,
    email_status    TEXT NOT NULL DEFAULT 'not_configured' CHECK (email_status IN ('not_configured', 'sent', 'failed')),
    read_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notifications_client ON public.notifications(client_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_case   ON public.notifications(case_id);

ALTER TABLE public.client_accounts    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.client_case_access ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.case_events        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications      ENABLE ROW LEVEL SECURITY;
